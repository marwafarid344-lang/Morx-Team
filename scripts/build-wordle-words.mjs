// Build script to generate lib/wordle/words.ts
import fs from 'fs';
import path from 'path';

// Canonical Wordle answers list (curated, clean, 5-letter common words)
async function run() {
  let targetWords = [];
  let validGuesses = [];

  try {
    console.log('Fetching official Wordle wordlists...');
    // Fetch official NYT wordle wordlist from reliable GitHub raw or public repository
    const targetRes = await fetch('https://raw.githubusercontent.com/3b1b/videos/master/_2022/wordle/data/possible_words.txt');
    if (targetRes.ok) {
      const text = await targetRes.text();
      targetWords = text.split('\n').map(w => w.trim().toUpperCase()).filter(w => w.length === 5);
      console.log(`Fetched ${targetWords.length} target words.`);
    }

    const validRes = await fetch('https://raw.githubusercontent.com/3b1b/videos/master/_2022/wordle/data/allowed_words.txt');
    if (validRes.ok) {
      const text = await validRes.text();
      validGuesses = text.split('\n').map(w => w.trim().toUpperCase()).filter(w => w.length === 5);
      console.log(`Fetched ${validGuesses.length} valid guess words.`);
    }
  } catch (err) {
    console.warn('Network fetch failed, using fallback curated list:', err.message);
  }

  // If network fetch failed or partial, ensure rich fallback list
  if (targetWords.length < 500) {
    targetWords = [
      "UPEND", "STAND", "MANGO", "CRANE", "SLATE", "AUDIO", "ROAST", "PLANT", "LIGHT", "DREAM",
      "BEACH", "FLAME", "SHINE", "CLOUD", "WATER", "HEART", "SPACE", "NIGHT", "POWER", "TRAIN",
      "BRAIN", "BREAD", "RIVER", "STONE", "CLEAN", "SMILE", "FRESH", "GREEN", "BLACK", "WHITE",
      "APPLE", "PEACH", "GRAPE", "CHAIR", "TABLE", "CLOCK", "HOUSE", "MOUSE", "HORSE", "MUSIC",
      "WORLD", "PEACE", "FAITH", "TRUST", "GUIDE", "SMART", "QUICK", "BRAVE", "HONOR", "GLORY",
      "CANDY", "SWEET", "STARS", "MOONS", "EARTH", "OCEAN", "TIGER", "EAGLE", "MAGIC", "STORY",
      "BLOOM", "CROWN", "DANCE", "FLASH", "GHOST", "GIANT", "HAPPY", "IMAGE", "JEWEL", "KNIFE",
      "LUNCH", "MONEY", "NOBLE", "OPERA", "PIANO", "QUEEN", "ROYAL", "SHARK", "TOWER", "UNITY",
      "VALOR", "WHALE", "YOUTH", "ZEBRA", "ALERT", "BLAZE", "CHARM", "DELTA", "ELITE", "FROST",
      "GRACE", "HAVEN", "IVORY", "JOKER", "KARMA", "LEMON", "MEDAL", "NURSE", "OASIS", "PILOT",
      "QUEST", "RADAR", "SOLAR", "TULIP", "URBAN", "VIGOR", "WHEAT", "YACHT", "VIVID", "PRIDE"
    ];
  }

  // Combine target words into valid guesses
  const allValid = new Set([...targetWords, ...validGuesses]);

  const fileContent = `// Autogenerated Wordle words repository
import { TileState } from './types';

export const TARGET_WORDS: string[] = ${JSON.stringify(targetWords)};

const VALID_SET = new Set<string>(${JSON.stringify(Array.from(allValid))});

export function isValidWord(word: string): boolean {
  if (!word || word.length !== 5) return false;
  const upper = word.toUpperCase();
  return VALID_SET.has(upper) || TARGET_WORDS.includes(upper);
}

export function evaluateGuess(guess: string, target: string): TileState[] {
  const g = guess.toUpperCase();
  const t = target.toUpperCase();
  const result: TileState[] = new Array(5).fill('absent');
  const targetLetterCounts: Record<string, number> = {};

  // Count letters in target
  for (let i = 0; i < 5; i++) {
    const char = t[i];
    targetLetterCounts[char] = (targetLetterCounts[char] || 0) + 1;
  }

  // Pass 1: find correct positions (Green)
  for (let i = 0; i < 5; i++) {
    if (g[i] === t[i]) {
      result[i] = 'correct';
      targetLetterCounts[g[i]]--;
    }
  }

  // Pass 2: find present letters in wrong positions (Yellow)
  for (let i = 0; i < 5; i++) {
    if (result[i] === 'correct') continue;
    const char = g[i];
    if (targetLetterCounts[char] && targetLetterCounts[char] > 0) {
      result[i] = 'present';
      targetLetterCounts[char]--;
    } else {
      result[i] = 'absent';
    }
  }

  return result;
}
`;

  fs.writeFileSync('lib/wordle/words.ts', fileContent, 'utf8');
  console.log(`Generated lib/wordle/words.ts with ${targetWords.length} targets and ${allValid.size} valid words.`);
}

run();
